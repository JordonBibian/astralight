"""Generate original, synthetic AV1 Main 8-bit SDR clips for GPU smoke tests.

Requires PyAV with the libsvtav1 encoder (tested with PyAV 19.0.2).
Run: python3 Tests/generate-av1-fixtures.py
No encoder library is linked into Astralight; the small encoded fixtures are
compiled into the explicitly invoked Debug diagnostic only.
"""
from fractions import Fraction
from io import BytesIO
from pathlib import Path
import av


def clip(width, height):
    buffer = BytesIO()
    muxer = av.open(buffer, "w", format="mp4")
    stream = muxer.add_stream("libsvtav1", rate=60)
    stream.width, stream.height = width, height
    stream.pix_fmt = "yuv420p"
    stream.codec_context.gop_size = 60
    stream.codec_context.color_primaries = 1  # BT.709
    stream.codec_context.color_trc = 1
    stream.codec_context.colorspace = 1
    stream.codec_context.color_range = 1  # limited range
    stream.options = {"preset": "10", "crf": "20", "svtav1-params": "pred-struct=1:lookahead=0:enable-tf=0:lp=2"}
    for number in range(16):
        frame = av.VideoFrame(width, height, "yuv420p")
        frame.pts, frame.time_base = number, Fraction(1, 60)
        frame.color_primaries = frame.color_trc = frame.colorspace = frame.color_range = 1
        for index, plane in enumerate(frame.planes):
            divisor = 1 if index == 0 else 2
            red, blue, green = ((63, 32, 173), (102, 240, 42), (240, 118, 26))[index]
            row = bytes([red]) * (plane.width // 2) + bytes([blue]) * (plane.width - plane.width // 2)
            row += bytes(plane.line_size - len(row))
            pixels = bytearray(row * plane.height)
            # A moving patch exercises temporal prediction; center color probes
            # continue to see red and blue in every decoded output frame.
            x = (number * 72) % (width - 64)
            for y in range(16 // divisor, 64 // divisor):
                begin = y * plane.line_size + x // divisor
                pixels[begin:begin + 64 // divisor] = bytes([green]) * (64 // divisor)
            plane.update(pixels)
        for packet in stream.encode(frame):
            muxer.mux(packet)
    for packet in stream.encode(None):
        muxer.mux(packet)
    muxer.close()
    demuxer = av.open(BytesIO(buffer.getvalue()))
    video = demuxer.streams.video[0]
    packets = [p for p in demuxer.demux(video) if p.size]
    assert len(packets) == 16 and packets[0].is_keyframe
    assert all(not p.is_keyframe for p in packets[1:]), "Require dependent frames"
    assert [p.pts for p in packets] == sorted(p.pts for p in packets), "Require low-delay frame order"
    configuration = video.codec_context.extradata
    assert configuration[0] == 0x81, "Require AV1CodecConfigurationRecord"
    print(f"{width}x{height}: {len(packets)} frames, {sum(p.size for p in packets)} bytes, av1C {configuration.hex()}")
    return b"".join(bytes(p) for p in packets), [p.size for p in packets], configuration


def byte_array(name, data):
    rows = [", ".join(f"0x{b:02x}" for b in data[i:i + 16]) for i in range(0, len(data), 16)]
    return f"static const unsigned char {name}[] = {{\n    " + ",\n    ".join(rows) + "\n};\n"


def main():
    sections = ["// Generated by generate-av1-fixtures.py using PyAV " + av.__version__ + ".\n"
                "// Original red/blue pattern with a moving green patch; AV1 Main8, BT.709 SDR.\n"
                "// Each clip contains one keyframe followed by 15 dependent frames.\n"
                "#pragma once\n"]
    sizes = [(640, 360), (1018, 700)]
    for index, (width, height) in enumerate(sizes):
        payload, lengths, config = clip(width, height)
        sections += [byte_array(f"ALAV1Data{index}", payload),
                     byte_array(f"ALAV1Configuration{index}", config),
                     f"static const size_t ALAV1Lengths{index}[] = {{{', '.join(map(str, lengths))}}};\n"]
    sections.append("typedef struct {\n    int width, height;\n    const unsigned char *data, *configuration;\n"
                    "    size_t configurationSize;\n    const size_t *lengths;\n    size_t frameCount;\n} ALAV1Fixture;\n"
                    "static const ALAV1Fixture ALAV1Fixtures[] = {\n")
    for index, (width, height) in enumerate(sizes):
        sections.append(f"    {{{width}, {height}, ALAV1Data{index}, ALAV1Configuration{index}, "
                        f"sizeof(ALAV1Configuration{index}), ALAV1Lengths{index}, "
                        f"sizeof(ALAV1Lengths{index}) / sizeof(size_t)}},\n")
    sections.append("};\n")
    Path(__file__).with_name("AV1TestFixtures.h").write_text("\n".join(sections))


if __name__ == "__main__":
    main()
